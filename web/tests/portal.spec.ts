test('manual proxy hides credentials and keeps domain and entry configuration', async ({ page }) => {
  await fixture(page); await page.goto('/')
  await page.getByRole('button', { name: '添加设备', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: '手动登录代理', exact: true }).click()
  await expect(page.getByLabel('账号', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('密码', { exact: true })).toHaveCount(0)
  await expect(dialog).toContainText('不会自动登录')
  await page.getByLabel('设备名称').fill('手动登录路由器')
  await page.getByLabel('设备内网地址').fill('https://192.168.1.1')
  await page.getByLabel('访问子域名').fill('manual-router')
  await page.getByRole('button', { name: '高级配置：入口路径与可信证书' }).click()
  await expect(page.getByLabel('入口路径')).toHaveAttribute('placeholder', '/')
  await page.getByLabel('入口路径').fill('/login')
  await page.getByLabel('证书验证方式').selectOption('pin')
  await page.getByLabel('设备证书 SHA-256 指纹').fill('11'.repeat(32))
  const saved = page.waitForRequest(r => r.url().endsWith('/api/services') && r.method() === 'POST')
  await page.getByRole('button', { name: '保存设备' }).click()
  const payload = (await saved).postDataJSON()
  expect(payload).toMatchObject({ type: 'proxy', entryPath: '/login', certificatePin: '11'.repeat(32) })
  expect(payload.credentials).toBeUndefined()
  const card = page.locator('.device-card').filter({ hasText: '手动登录路由器' })
  await expect(card).toContainText('代理访问 · 手动登录')
  await expect(page.locator('.stat').filter({ hasText: '自动登录已配置' }).locator('strong')).toHaveText('02')
})
