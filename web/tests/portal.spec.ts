import { test, expect, type Page } from '@playwright/test'

const devices = [
  { id: 'kvm', name: '主机 PiKVM', slug: 'pikvm', type: 'pikvm', upstreamUrl: 'https://192.168.1.100', entryPath: '/kvm/', group: '机房设备', notes: '主服务器远程控制', hasCredentials: true },
  { id: 'router', name: '核心路由', slug: 'router', type: 'openwrt', upstreamUrl: 'http://192.168.1.1', entryPath: '/cgi-bin/luci/', group: '网络设备', notes: 'OpenWrt 网络管理', hasCredentials: true },
  { id: 'nas', name: 'NAS 管理后台', slug: 'nas', type: 'link', upstreamUrl: 'https://192.168.1.20', entryPath: '/', group: '存储服务', notes: '文件与存储管理', hasCredentials: false },
]
async function fixture(page: Page) {
  let items = structuredClone(devices)
  await page.route('**/api/**', async route => {
    const req = route.request(), path = new URL(req.url()).pathname
    let body: unknown = {}
    if (path === '/api/me') body = { name: 'Admin', csrfToken: 'fixture-csrf', deviceDomain: 'console.xxx.com' }
    else if (path === '/api/services' && req.method() === 'GET') body = items
    else if (path === '/api/services' && req.method() === 'POST') {
      const { credentials, ...input } = req.postDataJSON()
      if (input.type === 'proxy') expect(credentials).toBeUndefined()
      else expect(credentials).toEqual({ username: 'admin', password: 'local-fixture-secret' })
      expect(req.headers()['x-csrf-token']).toBe('fixture-csrf')
      body = { ...input, id: 'new', hasCredentials: input.type !== 'proxy' }; items.push(body as typeof devices[number])
    } else if (path.endsWith('/test')) body = { message: '连接与自动登录验证通过' }
    else if (path.endsWith('/launch')) body = { url: 'about:blank#device-opened' }
    else if (req.method() === 'DELETE') { items = items.filter(s => path !== `/api/services/${s.id}`); body = { ok: true } }
    else if (path === '/api/logout') body = { ok: true }
    await route.fulfill({ json: body })
  })
}
